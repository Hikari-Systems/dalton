#!/bin/sh
# dalton entrypoint: validate the environment, render the fleet's site
# templates and the env-dependent config into /tmp, then exec nginx.
#
# The container runs read_only, so everything generated goes under /tmp (a
# tmpfs in the fleets' compose). Environment:
#
#   HS_API_KEY            required. The x-hs-api value CloudFront injects. An
#                         empty key would let every request without the header
#                         through, so dalton refuses to start without one.
#   MODSEC_RULE_ENGINE    On | DetectionOnly | Off. Default DetectionOnly; a
#                         fleet turns blocking on in its compose.
#   *_HOSTNAME, ENV_NAME, ENV_PREFIX
#                         substituted into the site templates (${NAME}).
#   OTEL_ENABLED          true | false (default true).
#   OTEL_EXPORTER_ENDPOINT
#                         OTLP/gRPC host:port (default otel-collector:4317,
#                         the node's Collector).
#   OTEL_SERVICE_NAME     default dalton.
#   OTEL_SAMPLE_RATIO     0.0-1.0 for requests without a sampled parent
#                         (default 1.0, as the controllers).
#   RATE_LIMIT            off | dry-run | on (default off). Per-client request
#                         rate limits: the mod_evasive the Apache image built
#                         but never enabled. dry-run logs what would be refused.
#   RATE_LIMIT_PAGE_RPS   per client IP, per URI (default 20, DOSPageCount).
#   RATE_LIMIT_SITE_RPS   per client IP, whole node (default 100, DOSSiteCount).
#   DALTON_SITES_DIR      where the sites are mounted (default /etc/nginx/templates).
set -eu

die() { echo "dalton: $*" >&2; exit 1; }

SITES_DIR="${DALTON_SITES_DIR:-/etc/nginx/templates}"
OUT=/tmp/nginx
MODSEC=/tmp/modsecurity

mkdir -p "$OUT/sites-enabled" "$OUT/client_body" "$OUT/proxy" "$OUT/fastcgi" \
         "$OUT/uwsgi" "$OUT/scgi" "$MODSEC/tmp" "$MODSEC/data"
rm -f "$OUT/sites-enabled/"*.conf

# ------------------------------------------------------------------ x-hs-api
[ -n "${HS_API_KEY:-}" ] || die "HS_API_KEY is not set; refusing to start (every request would be denied, or with an empty key, allowed)"
# The key is matched case-sensitively as a literal regex (\Q…\E): nginx's
# plain-string map matching ignores case, Apache's comparison didn't.
case "$HS_API_KEY" in
  *[!A-Za-z0-9._~+/=:@%^!*,-]*) die "HS_API_KEY contains characters dalton can't place safely in its config (allowed: A-Z a-z 0-9 . _ ~ + / = : @ % ^ ! * , -)";;
esac
[ "${#HS_API_KEY}" -ge 16 ] || die "HS_API_KEY is shorter than 16 characters"
cat > "$OUT/hs-api.conf" <<EOF
# Generated by docker-entrypoint.sh.
map \$http_x_hs_api \$hs_api_ok {
    default 0;
    "~^\\Q${HS_API_KEY}\\E\$" 1;
}
# The MCP connector landing page (/ and /index.html) is public.
map "\$hs_api_ok:\$uri" \$hs_api_ok_or_landing {
    default 0;
    "~^1:" 1;
    "~^0:/(index\\.html)?\$" 1;
}
EOF

# ------------------------------------------------------------------ ModSecurity
ENGINE="${MODSEC_RULE_ENGINE:-DetectionOnly}"
case "$ENGINE" in
  On|DetectionOnly|Off) ;;
  *) die "MODSEC_RULE_ENGINE must be On, DetectionOnly or Off (got '$ENGINE')";;
esac
printf '# Generated by docker-entrypoint.sh from MODSEC_RULE_ENGINE.\nSecRuleEngine %s\n' "$ENGINE" > "$MODSEC/engine.conf"

# ------------------------------------------------------------------ resolver
# The container's own DNS server (podman's aardvark-dns, docker's 127.0.0.11),
# so upstream names are re-resolved at run time.
NS=$(awk '/^nameserver/ { ip = $2; if (ip ~ /:/) ip = "[" ip "]"; printf "%s ", ip }' /etc/resolv.conf)
[ -n "$NS" ] || die "no nameserver in /etc/resolv.conf"
printf '# Generated by docker-entrypoint.sh from /etc/resolv.conf.\nresolver %svalid=10s ipv6=off;\n' "$NS" > "$OUT/resolver.conf"

# ------------------------------------------------------------------ OpenTelemetry
OTEL_ENDPOINT="${OTEL_EXPORTER_ENDPOINT:-otel-collector:4317}"
OTEL_SERVICE="${OTEL_SERVICE_NAME:-dalton}"
RATIO="${OTEL_SAMPLE_RATIO:-1.0}"
PCT=$(awk -v r="$RATIO" 'BEGIN { if (r !~ /^[0-9]*\.?[0-9]+$/ || r > 1) exit 1; printf "%.2f", r * 100 }') \
  || die "OTEL_SAMPLE_RATIO must be between 0 and 1 (got '$RATIO')"
case "$OTEL_ENDPOINT$OTEL_SERVICE${ENV_NAME:-}" in
  *[\"\;\{\}\\\$\ ]*) die "OTEL_EXPORTER_ENDPOINT, OTEL_SERVICE_NAME and ENV_NAME must not contain quotes, spaces, \$, ; or braces";;
esac
if [ "${OTEL_ENABLED:-true}" = "true" ]; then
  cat > "$OUT/otel.conf" <<EOF
# Generated by docker-entrypoint.sh.
# Spans go over OTLP/gRPC to the node's Collector, which holds the backend's
# key and stamps deployment.environment; dalton needs no secret.
otel_exporter {
    endpoint ${OTEL_ENDPOINT};
    interval 5s;
    batch_size 512;
    batch_count 4;
}
otel_service_name "${OTEL_SERVICE}";
otel_resource_attr deployment.environment.name "${ENV_NAME:-unknown}";

# Continue an incoming W3C traceparent and send dalton's own on to the
# upstream, so controller spans are children of dalton's.
otel_trace_context propagate;

# A sampled parent is always followed; otherwise sample OTEL_SAMPLE_RATIO.
split_clients "\$otel_trace_id" \$dalton_ratio_sampled {
    ${PCT}% on;
    *       off;
}
map \$otel_parent_sampled \$dalton_otel_trace {
    "1"     on;
    default \$dalton_ratio_sampled;
}
otel_trace \$dalton_otel_trace;

otel_span_attr client.address  \$remote_addr;
otel_span_attr server.address  \$host;
otel_span_attr url.path        \$uri;
otel_span_attr dalton.modsecurity.engine "${ENGINE}";
EOF
else
  # The module wants an exporter block even when nothing is traced.
  printf '# Generated by docker-entrypoint.sh: OTEL_ENABLED=%s.\notel_exporter { endpoint %s; }\notel_trace off;\n' \
    "${OTEL_ENABLED}" "${OTEL_ENDPOINT}" > "$OUT/otel.conf"
fi

# ------------------------------------------------------------------ rate limits
# mod_evasive's thresholds as nginx limit_req: requests a second per client IP
# (the real one, after the CloudFront/ALB hops), per URI and for the whole
# node, each allowed a burst of one second's worth. Private addresses (the
# ALB's health checks, other containers) are never limited, as DOSWhitelist
# had it; a location can opt out with snippets/ratelimit-exempt.conf. Over the
# limit is 429. (mod_evasive also banned an IP for DOSBlockingPeriod; nginx
# has no ban, only the rate.)
RL="${RATE_LIMIT:-off}"
PAGE="${RATE_LIMIT_PAGE_RPS:-20}"
SITE="${RATE_LIMIT_SITE_RPS:-100}"
case "$RL" in off|dry-run|on) ;; *) die "RATE_LIMIT must be off, dry-run or on (got '$RL')";; esac
case "$PAGE$SITE" in ''|*[!0-9]*) die "RATE_LIMIT_PAGE_RPS and RATE_LIMIT_SITE_RPS must be whole numbers";; esac
[ "$PAGE" -gt 0 ] && [ "$SITE" -gt 0 ] || die "RATE_LIMIT_PAGE_RPS and RATE_LIMIT_SITE_RPS must be above 0"
if [ "$RL" = off ]; then
  printf '# Generated by docker-entrypoint.sh: RATE_LIMIT=off.\n' > "$OUT/ratelimit.conf"
else
  DRY=off; [ "$RL" = dry-run ] && DRY=on
  cat > "$OUT/ratelimit.conf" <<RLCONF
# Generated by docker-entrypoint.sh: RATE_LIMIT=${RL}.
# An empty key isn't counted: exempt clients and opted-out locations get one.
map \$dalton_rl_exempt \$dalton_rl_site_key {
    "0"     \$binary_remote_addr;
    default "";
}
map \$dalton_rl_exempt \$dalton_rl_page_key {
    "0"     \$binary_remote_addr\$uri;
    default "";
}
limit_req_zone \$dalton_rl_site_key zone=dalton_site:10m rate=${SITE}r/s;
limit_req_zone \$dalton_rl_page_key zone=dalton_page:20m rate=${PAGE}r/s;
limit_req zone=dalton_site burst=${SITE} nodelay;
limit_req zone=dalton_page burst=${PAGE} nodelay;
limit_req_status 429;
limit_req_log_level warn;
limit_req_dry_run ${DRY};
RLCONF
fi

# ------------------------------------------------------------------ sites
# Each site is an nginx server{} with ${VAR} placeholders. Only the variables
# below are substituted, so nginx's own \$variables pass through untouched.
VARS=$(env | awk -F= '$1 ~ /(_HOSTNAME|^ENV_NAME|^ENV_PREFIX|^BRANCH_NAME)$/ { printf "${%s} ", $1 }')
found=0
for src in "$SITES_DIR"/*.conf "$SITES_DIR"/*.conf.template; do
  [ -f "$src" ] || continue
  found=1
  name=$(basename "$src" .template)
  envsubst "$VARS" < "$src" > "$OUT/sites-enabled/$name"
  # A placeholder left unrendered means the compose lacks that variable:
  # nginx would otherwise serve a vhost named "${FOO_HOSTNAME}".
  # (Commented-out lines, such as a disabled site, don't count.)
  left=$(grep -vE '^[[:space:]]*#' "$OUT/sites-enabled/$name" | grep -oE '\$\{[A-Z0-9_]+\}' | sort -u | tr '\n' ' ' || true)
  [ -z "$left" ] || die "$name uses ${left}but the environment doesn't set it"
done
[ "$found" = 1 ] || die "no sites in $SITES_DIR (mount the fleet's sites directory there)"

if [ "$#" -eq 0 ]; then
  set -- nginx -e stderr -g 'daemon off;'
fi
if [ "$1" = nginx ]; then
  nginx -e stderr -t -q || die "nginx configuration test failed"
fi
exec "$@"
