#!/usr/bin/env python3
"""Write dalton/realip-cloudfront.conf from AWS's ip-ranges.json.

Trusted as proxies (nginx set_real_ip_from), so the client address is the
first untrusted hop in X-Forwarded-For:
  * the private ranges (the ALB, the container network),
  * every CLOUDFRONT_ORIGIN_FACING prefix: the addresses CloudFront connects
    to the ALB from, which the ALB appends to X-Forwarded-For,
  * scripts/cloudfront-legacy.txt: the 23 prefixes the Apache image trusted
    (CLOUDFRONT in eu-west-1/2 and us-east-1, plus 64.252.64.0/18), kept so
    nothing that resolved before resolves differently now.

Refresh: curl -so ip-ranges.json https://ip-ranges.amazonaws.com/ip-ranges.json
         python3 scripts/gen-realip.py
"""
import ipaddress
import json
import pathlib

root = pathlib.Path(__file__).resolve().parent.parent
ranges = json.loads((root / "ip-ranges.json").read_text())
legacy = (root / "scripts" / "cloudfront-legacy.txt").read_text().split()
origin_facing = {p["ip_prefix"] for p in ranges["prefixes"]
                 if p["service"] == "CLOUDFRONT_ORIGIN_FACING"}
cidrs = sorted(origin_facing | set(legacy), key=ipaddress.ip_network)

lines = [
    "# Generated by scripts/gen-realip.py from ip-ranges.json "
    f"(createDate {ranges['createDate']}). Do not edit by hand.",
    "set_real_ip_from 10.0.0.0/8;",
    "set_real_ip_from 172.16.0.0/12;",
    "set_real_ip_from 192.168.0.0/16;",
    "set_real_ip_from 127.0.0.1;",
]
lines += [f"set_real_ip_from {c};" for c in cidrs]
lines += ["real_ip_header X-Forwarded-For;", "real_ip_recursive on;", ""]
(root / "dalton" / "realip-cloudfront.conf").write_text("\n".join(lines))
print(f"{len(cidrs)} CloudFront prefixes ({len(origin_facing)} origin-facing)")
